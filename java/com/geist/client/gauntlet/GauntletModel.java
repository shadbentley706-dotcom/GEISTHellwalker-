    /** Slim arms are a pixel narrower: slide the bracers half a pixel toward the body so they stay centred. */
    public void setSlim(boolean slim) {
        gRight.x = slim ? 0.5F : 0.0F;
        gLeft.x = slim ? -0.5F : 0.0F;
        sRight.x = slim ? 0.5F : 0.0F;
        sLeft.x = slim ? -0.5F : 0.0F;
        ghostRight.x = slim ? 0.5F : 0.0F;
        ghostLeft.x = slim ? -0.5F : 0.0F;
    }

    /** Show the armour (on players) or only the line-art mannequin (second pass of the inventory icon). */
    public void showGhost(boolean ghost) {
        gBody.visible = gRight.visible = gLeft.visible = sRight.visible = sLeft.visible = !ghost;
        ghostBody.visible = ghostRight.visible = ghostLeft.visible = ghost;
    }

    public void hideGhost() {
        gBody.visible = gRight.visible = gLeft.visible = sRight.visible = sLeft.visible = true;
        ghostBody.visible = ghostRight.visible = ghostLeft.visible = false;
    }

    /** Only the right forearm bracer (the inventory icon). Undo with {@link #hideGhost()}. */
    public void bracerOnly() {
        hideGhost();
        gBody.visible = gLeft.visible = sRight.visible = sLeft.visible = false;
    }

    /** Puts the moving parts back to rest (the animator then pushes them). */
    public void resetMoving() {
        rodFR.resetPose();
        rodBR.resetPose();
        rodFL.resetPose();
        rodBL.resetPose();
        flapR.resetPose();
        flapL.resetPose();
    }
