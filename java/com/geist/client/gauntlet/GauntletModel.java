    public final ModelPart rodFR, rodBR, rodFL, rodBL, flapR, flapL;

    public GauntletModel(ModelPart root) {
        super(root);
        this.gBody = this.body.getChild("gaunt");
        this.gRight = this.rightArm.getChild("gaunt");
        this.gLeft = this.leftArm.getChild("gaunt");
        this.sRight = this.rightArm.getChild("shoulder");
        this.sLeft = this.leftArm.getChild("shoulder");
        this.ghostBody = this.body.getChild("ghost");
        this.ghostRight = this.rightArm.getChild("ghost");
        this.ghostLeft = this.leftArm.getChild("ghost");
        this.rodFR = this.gRight.getChild("rod_f");
        this.rodBR = this.gRight.getChild("rod_b");
        this.rodFL = this.gLeft.getChild("rod_f");
        this.rodBL = this.gLeft.getChild("rod_b");
        this.flapR = this.gRight.getChild("flap");
        this.flapL = this.gLeft.getChild("flap");
    }

