    public final ModelPart spineRodR, spineRodL, thighRodR, thighRodL;

    public ExoModel(ModelPart root) {
        super(root);
        this.exoBody = this.body.getChild("exo");
        this.exoRight = this.rightLeg.getChild("exo");
        this.exoLeft = this.leftLeg.getChild("exo");
        this.ghostBody = this.body.getChild("ghost");
        this.ghostRight = this.rightLeg.getChild("ghost");
        this.ghostLeft = this.leftLeg.getChild("ghost");
        this.spineRodR = this.exoBody.getChild("spine_rod_r");
        this.spineRodL = this.exoBody.getChild("spine_rod_l");
        this.thighRodR = this.exoRight.getChild("thigh_rod");
        this.thighRodL = this.exoLeft.getChild("thigh_rod");
    }

