    /** Show the frame (on players) or only the line-art mannequin (second pass of the inventory icon). */
    public void showGhost(boolean ghost) {
        exoBody.visible = exoRight.visible = exoLeft.visible = !ghost;
        ghostBody.visible = ghostRight.visible = ghostLeft.visible = ghost;
    }

    public void hideGhost() {
        exoBody.visible = exoRight.visible = exoLeft.visible = true;
        ghostBody.visible = ghostRight.visible = ghostLeft.visible = false;
    }

    /** Puts the moving pistons back to rest (the animator then pushes them). */
    public void resetPistons() {
        spineRodR.resetPose();
        spineRodL.resetPose();
        thighRodR.resetPose();
        thighRodL.resetPose();
    }
