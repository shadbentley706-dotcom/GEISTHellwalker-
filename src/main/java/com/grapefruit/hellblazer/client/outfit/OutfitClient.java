import net.minecraftforge.client.ForgeHooksClient;
import net.minecraftforge.client.event.EntityRenderersEvent;
import net.minecraftforge.client.extensions.common.IClientItemExtensions;
import net.minecraftforge.eventbus.api.SubscribeEvent;
import net.minecraftforge.fml.common.Mod;

/**
 * The specialist's clothes on the client. Worn, each piece is drawn on its own model cut close to the body
 * (OutfitModels, generated by tools/gen_outfit.py): the coat over the torso and arms - with a slim-armed cut of sleeve
 * for slim skins - and its skirts riding on the legs, open down the front so the black trousers show between them. In
 * the inventory each piece is shown as itself in 3D, turned three-quarters to you.
 */
public final class OutfitClient {
    public static final ModelLayerLocation COAT = new ModelLayerLocation(new ResourceLocation(HellblazerMod.MODID, "coat"), "main");
    public static final ModelLayerLocation TROUSERS = new ModelLayerLocation(new ResourceLocation(HellblazerMod.MODID, "trousers"), "main");
    private static final ResourceLocation COAT_TEX = new ResourceLocation(HellblazerMod.MODID, "textures/models/armor/coat.png");
    private static final ResourceLocation TROUSERS_TEX = new ResourceLocation(HellblazerMod.MODID, "textures/models/armor/trousers.png");
    private static HumanoidModel<LivingEntity> coat, trousers;

    private OutfitClient() {}

    @Mod.EventBusSubscriber(modid = HellblazerMod.MODID, bus = Mod.EventBusSubscriber.Bus.MOD, value = Dist.CLIENT)
    public static final class Setup {
        private Setup() {}

        @SubscribeEvent
        public static void onLayers(EntityRenderersEvent.RegisterLayerDefinitions event) {
            event.registerLayerDefinition(COAT, OutfitModels::coat);
            event.registerLayerDefinition(TROUSERS, OutfitModels::trousers);
        }

        @SubscribeEvent
        public static void onReload(EntityRenderersEvent.AddLayers event) {
            coat = null;                                                           // re-baked on next use after a resource reload
            trousers = null;
        }
    }

    static HumanoidModel<LivingEntity> coat() {
        if (coat == null) coat = new HumanoidModel<>(Minecraft.getInstance().getEntityModels().bakeLayer(COAT));
        return coat;
    }

    static HumanoidModel<LivingEntity> trousers() {
        if (trousers == null) trousers = new HumanoidModel<>(Minecraft.getInstance().getEntityModels().bakeLayer(TROUSERS));
        return trousers;
    }

    /** One cut of sleeve or the other. */
    private static void sleeves(HumanoidModel<LivingEntity> m, boolean slim) {
        m.rightArm.getChild("right_sleeve").visible = !slim;
        m.leftArm.getChild("left_sleeve").visible = !slim;
        m.rightArm.getChild("right_sleeve_slim").visible = slim;
        m.leftArm.getChild("left_sleeve_slim").visible = slim;
    }

    public static final IClientItemExtensions EXT = new IClientItemExtensions() {
        @Override
        public HumanoidModel<?> getHumanoidArmorModel(LivingEntity e, ItemStack stack, EquipmentSlot slot, HumanoidModel<?> original) {
            return slot == EquipmentSlot.LEGS ? trousers() : coat();
        }

        @Override
        public Model getGenericArmorModel(LivingEntity e, ItemStack stack, EquipmentSlot slot, HumanoidModel<?> original) {
            if (slot != EquipmentSlot.CHEST) return IClientItemExtensions.super.getGenericArmorModel(e, stack, slot, original);
            HumanoidModel<LivingEntity> m = coat();
            ForgeHooksClient.copyModelProperties(original, m);
            // the coat's skirts hang from the legs, so the legs are drawn too (they carry nothing else)
            m.head.visible = false;
            m.hat.visible = false;
            m.body.visible = true;
            m.rightArm.visible = true;
            m.leftArm.visible = true;
            m.rightLeg.visible = true;
            m.leftLeg.visible = true;
            sleeves(m, e instanceof AbstractClientPlayer p && "slim".equals(p.getModelName()));
            return m;
        }

        @Override
        public BlockEntityWithoutLevelRenderer getCustomRenderer() {
            return Piece.get();
        }
    };

    /** A piece of the outfit drawn as itself. */
    public static final class Piece extends BlockEntityWithoutLevelRenderer {
        private static Piece instance;

        private Piece() {
            super(Minecraft.getInstance().getBlockEntityRenderDispatcher(), Minecraft.getInstance().getEntityModels());
        }

        static Piece get() {
            if (instance == null) instance = new Piece();
            return instance;
        }

        @Override
        public void renderByItem(ItemStack stack, ItemDisplayContext ctx, PoseStack ps, MultiBufferSource buffers, int light, int overlay) {
            if (!(stack.getItem() instanceof OutfitItem piece)) return;
            boolean legs = piece.getType() == ArmorItem.Type.LEGGINGS;
            HumanoidModel<LivingEntity> m = legs ? trousers() : coat();
            m.young = false;                                                       // models start out "young" (half size, low) until worn
            m.riding = false;
            m.crouching = false;
            m.attackTime = 0.0F;
            for (ModelPart p : new ModelPart[]{m.head, m.hat, m.body, m.rightArm, m.leftArm, m.rightLeg, m.leftLeg}) {
                p.resetPose();
                p.visible = false;
            }
            float cy, size;
            m.body.visible = true;
            m.rightLeg.visible = m.leftLeg.visible = true;
            if (legs) {
                m.rightLeg.zRot = 0.04F;
                m.leftLeg.zRot = -0.04F;
                cy = 15.0F;
                size = 0.95F;
            } else {
                m.rightArm.visible = m.leftArm.visible = true;
                sleeves(m, false);
                m.rightArm.zRot = 0.12F;
                m.leftArm.zRot = -0.12F;
                cy = 9.5F;
                size = 0.78F;
            }
            ps.pushPose();
            ps.translate(0.5F, 0.5F, 0.5F);
            boolean inv = ctx == ItemDisplayContext.GUI || ctx == ItemDisplayContext.FIXED;
            if (inv) {
                ps.mulPose(Axis.XP.rotationDegrees(12.0F));
                ps.mulPose(Axis.YP.rotationDegrees(28.0F));
            } else if (ctx.firstPerson() || ctx == ItemDisplayContext.THIRD_PERSON_LEFT_HAND || ctx == ItemDisplayContext.THIRD_PERSON_RIGHT_HAND) {
                size *= 0.5F;
                ps.translate(0.0F, 0.1F, 0.0F);
                ps.mulPose(Axis.YP.rotationDegrees(ctx.firstPerson() ? -60.0F : 90.0F));
            } else {
                size *= 0.6F;
            }
            ps.scale(size, size, size);
            ps.mulPose(Axis.XP.rotationDegrees(180.0F));                       // model space: y down, front to -z
            ps.translate(0.0F, -cy / 16.0F, 0.0F);
            m.renderToBuffer(ps, ItemRenderer.getArmorFoilBuffer(buffers, RenderType.armorCutoutNoCull(legs ? TROUSERS_TEX : COAT_TEX), false, stack.hasFoil()),
                    light, OverlayTexture.NO_OVERLAY, 1.0F, 1.0F, 1.0F, 1.0F);
            ps.popPose();
        }
    }
}
